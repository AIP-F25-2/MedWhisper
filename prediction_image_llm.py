from fastapi import FastAPI, UploadFile, File
from tensorflow.keras.models import load_model
from tensorflow.keras.preprocessing import image
import numpy as np
from io import BytesIO
from PIL import Image
from transformers import pipeline  # Hugging Face model

# Initialize the FastAPI app
app = FastAPI()

# Load your .h5 models
model1 = load_model('/path_to_models/cervicalcancermodel.h5')
model2 = load_model('/path_to_models/eye_model.h5')
model3 = load_model('/path_to_models/pneumonia_model.h5')
model4 = load_model('/path_to_models/wound_model.h5')
model5 = load_model('/path_to_models/hairloss_model.h5')
model6 = load_model('/path_to_models/lungcancer_model.h5')
model7 = load_model('/path_to_models/brokefracture_model.h5')

# Load the LLM model for generating explanations
llm = pipeline('text-generation', model='gpt-2')  # You can switch to GPT-3 or other models if needed

# Function to preprocess image
def preprocess_image(image_bytes: bytes):
    img = Image.open(BytesIO(image_bytes))
    img = img.resize((224, 224))  # Resize to match model input size
    img_array = np.array(img)  # Convert to numpy array
    img_array = np.expand_dims(img_array, axis=0)  # Add batch dimension
    img_array = img_array / 255.0  # Normalize
    return img_array

# Prediction function for all models
def predict_with_models(img_array):
    result1 = model1.predict(img_array)
    result2 = model2.predict(img_array)
    result3 = model3.predict(img_array)
    result4 = model4.predict(img_array)
    result5 = model5.predict(img_array)
    result6 = model6.predict(img_array)
    result7 = model7.predict(img_array)

    predictions = {
        "cervical_cancer": result1.tolist(),
        "eye_condition": result2.tolist(),
        "pneumonia": result3.tolist(),
        "wound_condition": result4.tolist(),
        "hair_loss": result5.tolist(),
        "lung_cancer": result6.tolist(),
        "broken_fracture": result7.tolist()
    }

    return predictions

# Function to generate an explanation using LLM
def generate_explanation(predictions):
    # Convert the predictions to a string that LLM can process
    explanation_input = f"Explain the following medical conditions based on predictions:\n"
    for condition, prediction in predictions.items():
        explanation_input += f"{condition}: {prediction}\n"

    explanation = llm(explanation_input, max_length=150, num_return_sequences=1)[0]['generated_text']
    return explanation

# API endpoint to process the image, get predictions, and provide explanations
@app.post("/predict/")
async def predict(file: UploadFile = File(...)):
    image_bytes = await file.read()  # Read the uploaded image
    img_array = preprocess_image(image_bytes)  # Preprocess the image
    predictions = predict_with_models(img_array)  # Get predictions from models
    explanation = generate_explanation(predictions)  # Get explanation from LLM

    return {"predictions": predictions, "explanation": explanation}